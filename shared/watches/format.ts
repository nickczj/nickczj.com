import type { MovementType, WatchInput, WatchStatus } from './schema'

// Pure helpers shared by the watch pages, the photo script, and tests.
// Type-only imports keep zod out of the client bundle.

export interface PhotoManifestEntry {
  /** Content hash of the original; part of every variant's file name. */
  v: string
  /** Oriented width and height of the largest variant. */
  w: number
  h: number
  /** Widths that exist for each format, ascending. */
  widths: number[]
  /** Dominant colour, used as the placeholder while the image loads. For product shots, the tile's background. */
  color: string
  /** A maker's product shot padded onto a plain tile (`--product`); shown uncropped. */
  product?: boolean
}

/** slug → photo id → entry. Generated by `scripts/watch-photos.ts`. */
export type PhotoManifest = Record<string, Record<string, PhotoManifestEntry>>

export const PHOTO_FORMATS = [
  { ext: 'avif', contentType: 'image/avif' },
  { ext: 'jpg', contentType: 'image/jpeg' }
] as const

export type PhotoExt = (typeof PHOTO_FORMATS)[number]['ext']

export function photoKey(slug: string, id: string, v: string, width: number, ext: PhotoExt): string {
  return `watches/${slug}/${id}.${v}-${width}.${ext}`
}

export interface PhotoSources {
  avif: string
  jpg: string
  fallback: string
  full: string
  social: string
  width: number
  height: number
  color: string
  product: boolean
}

export function photoSources(
  manifest: PhotoManifest,
  mediaBaseUrl: string,
  slug: string,
  id: string
): PhotoSources | null {
  const entry = manifest[slug]?.[id]
  if (!entry || entry.widths.length === 0) return null

  const base = mediaBaseUrl.replace(/\/+$/, '')
  const url = (width: number, ext: PhotoExt) => `${base}/${photoKey(slug, id, entry.v, width, ext)}`
  const srcset = (ext: PhotoExt) => entry.widths.map(width => `${url(width, ext)} ${width}w`).join(', ')
  const largest = entry.widths[entry.widths.length - 1]!
  const social = entry.widths.find(width => width >= 1200) ?? largest

  return {
    avif: srcset('avif'),
    jpg: srcset('jpg'),
    fallback: url(entry.widths.find(width => width >= 1600) ?? largest, 'jpg'),
    full: url(largest, 'jpg'),
    social: url(social, 'jpg'),
    width: entry.w,
    height: entry.h,
    color: entry.color,
    product: entry.product === true
  }
}

const MOVEMENT_LABELS: Record<MovementType, string> = {
  automatic: 'Automatic',
  manual: 'Hand-wound',
  quartz: 'Quartz',
  'spring-drive': 'Spring Drive',
  solar: 'Solar'
}

export function movementLabel(type: MovementType): string {
  return MOVEMENT_LABELS[type]
}

export function isMechanical(type: MovementType): boolean {
  return type === 'automatic' || type === 'manual'
}

const STATUS_LABELS: Record<WatchStatus, string> = {
  owned: 'In the collection',
  sold: 'Previously owned',
  admired: 'Admired'
}

export function statusLabel(status: WatchStatus): string {
  return STATUS_LABELS[status]
}

/**
 * Whether the Markdown body has any content. Admired watches only get a
 * detail page when they have a write-up; otherwise the card is the whole entry.
 */
export function hasWriteUp(watch: { body?: { value?: unknown[] } | null }): boolean {
  return (watch.body?.value?.length ?? 0) > 0
}

type AdmiredSortSource = Pick<WatchInput, 'brand' | 'title'>

/** Admired watches have no acquisition year, so sort them by brand, then title. */
export function compareAdmired(a: AdmiredSortSource, b: AdmiredSortSource): number {
  return a.brand.localeCompare(b.brand) || a.title.localeCompare(b.title)
}

export interface AdmiredSection<T> {
  key: 'shortlist' | 'admired'
  title: string
  items: T[]
}

/**
 * The shortlist first, then everything else, each sorted by brand and title.
 * Empty sections are dropped. Nuxt Content stores a missing `shortlist` as null.
 */
export function admiredSections<T extends AdmiredSortSource & { shortlist?: boolean | null }>(
  watches: T[]
): AdmiredSection<T>[] {
  const shortlist = watches.filter(watch => watch.shortlist === true).sort(compareAdmired)
  const rest = watches.filter(watch => watch.shortlist !== true).sort(compareAdmired)
  return [
    { key: 'shortlist' as const, title: 'Shortlist', items: shortlist },
    { key: 'admired' as const, title: shortlist.length ? 'Everything else' : 'Admired', items: rest }
  ].filter(section => section.items.length)
}

/** Who took the photos shown on a page: the credits of each watch's first photo, deduplicated and sorted. */
export function photoCredits(watches: { photos?: { credit?: string | null }[] | null }[]): string[] {
  const credits = watches
    .map(watch => watch.photos?.[0]?.credit)
    .filter((credit): credit is string => Boolean(credit))
  return [...new Set(credits)].sort((a, b) => a.localeCompare(b))
}

// Two decimals: makers quote sizes like 44.25 mm and 9.95 mm.
const number = new Intl.NumberFormat('en-SG', { maximumFractionDigits: 2 })

export function formatNumber(value: number): string {
  return number.format(value)
}

/** Signed rate with a real minus sign: "+4 s/day", "−2.5 s/day", "±0 s/day". */
export function formatRate(secondsPerDay: number): string {
  if (secondsPerDay === 0) return '±0 s/day'
  const sign = secondsPerDay > 0 ? '+' : '−'
  return `${sign}${number.format(Math.abs(secondsPerDay))} s/day`
}

export function formatBeat(vph: number): string {
  return `${number.format(vph)} vph · ${number.format(vph / 3600)} beats/s`
}

type SpecSource = Pick<WatchInput, 'movement' | 'case'>

/** One-line summary for cards: "40.5 mm · 6R35 · Automatic". */
export function specLine(watch: SpecSource): string {
  const parts: string[] = []
  if (watch.case?.diameter_mm) parts.push(`${number.format(watch.case.diameter_mm)} mm`)
  if (watch.movement.caliber) parts.push(watch.movement.caliber)
  parts.push(movementLabel(watch.movement.type))
  return parts.join(' · ')
}

export interface SpecRow {
  label: string
  value: string
}

type SpecRowSource = Pick<
  WatchInput,
  'movement' | 'case' | 'complications' | 'water_resistance_m' | 'crystal' | 'dial' | 'strap' | 'reference'
>

export function specRows(watch: SpecRowSource): SpecRow[] {
  const rows: SpecRow[] = []
  const add = (label: string, value: string | undefined | null) => {
    if (value) rows.push({ label, value })
  }
  const { movement } = watch
  const c = watch.case ?? {}

  add('Reference', watch.reference)
  add('Movement', [movementLabel(movement.type), movement.caliber].filter(Boolean).join(', '))
  add('Based on', movement.base)
  add('Beat rate', movement.vph ? formatBeat(movement.vph) : null)
  add('Power reserve', movement.power_reserve_h ? `${number.format(movement.power_reserve_h)} hours` : null)
  add('Jewels', movement.jewels != null ? String(movement.jewels) : null)
  add('Certification', movement.certification)

  const features = [
    movement.hacking === true ? 'hacking seconds' : null,
    movement.hacking === false ? 'non-hacking' : null,
    movement.type === 'automatic' && movement.hand_winding === true ? 'hand-winding' : null,
    movement.type === 'automatic' && movement.hand_winding === false ? 'no hand-winding' : null
  ].filter(Boolean)
  add('Features', features.length ? capitalise(features.join(', ')) : null)
  add('Complications', watch.complications?.length ? capitalise(watch.complications.join(', ')) : null)

  const size = [
    c.diameter_mm ? `${number.format(c.diameter_mm)} mm wide` : null,
    c.thickness_mm ? `${number.format(c.thickness_mm)} mm thick` : null,
    c.lug_to_lug_mm ? `${number.format(c.lug_to_lug_mm)} mm lug to lug` : null
  ].filter(Boolean)
  add('Case', size.length ? size.join(', ') : null)
  add('Case material', c.material ? capitalise(c.material) : null)
  add('Case back', c.back ? capitalise(c.back) : null)
  add('Lug width', c.lug_width_mm ? `${number.format(c.lug_width_mm)} mm` : null)
  add('Water resistance', watch.water_resistance_m != null ? `${number.format(watch.water_resistance_m)} m` : null)
  add('Crystal', watch.crystal ? capitalise(watch.crystal) : null)
  add('Dial', watch.dial ? capitalise(watch.dial) : null)
  add('Strap', watch.strap ? capitalise(watch.strap) : null)

  return rows
}

type StatSource = Pick<WatchInput, 'brand' | 'status' | 'movement' | 'case'>

export interface CollectionStat {
  label: string
  value: string
}

export function collectionStats(watches: StatSource[]): CollectionStat[] {
  const owned = watches.filter(watch => (watch.status ?? 'owned') === 'owned')
  if (!owned.length) return []

  const stats: CollectionStat[] = [{ label: 'Owned', value: String(owned.length) }]

  const counts = new Map<MovementType, number>()
  for (const watch of owned) counts.set(watch.movement.type, (counts.get(watch.movement.type) ?? 0) + 1)
  const movements = [...counts.entries()]
    .sort((a, b) => b[1] - a[1])
    .map(([type, count]) => `${count} ${movementLabel(type).toLowerCase()}`)
  stats.push({ label: 'Movements', value: movements.join(' · ') })

  const brands = new Set(owned.map(watch => watch.brand.trim().toLowerCase()))
  stats.push({ label: 'Brands', value: String(brands.size) })

  const sizes = owned.map(watch => watch.case?.diameter_mm).filter((size): size is number => typeof size === 'number')
  if (sizes.length) {
    const min = Math.min(...sizes)
    const max = Math.max(...sizes)
    stats.push({
      label: 'Case sizes',
      value: min === max ? `${number.format(min)} mm` : `${number.format(min)}–${number.format(max)} mm`
    })
  }

  return stats
}

type SortSource = Pick<WatchInput, 'title' | 'acquired'>

/** Newest acquisition first; undated watches after dated ones; then by title. */
export function compareWatches(a: SortSource, b: SortSource): number {
  const ay = a.acquired ?? -Infinity
  const by = b.acquired ?? -Infinity
  if (ay !== by) return by - ay
  return a.title.localeCompare(b.title)
}

function capitalise(value: string): string {
  return value.charAt(0).toUpperCase() + value.slice(1)
}
